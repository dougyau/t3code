type Target = typeof C.WorkerTarget.Type;
export interface WorkerViewer {
  readonly session: EnvironmentAuth.AuthenticatedSession;
  /** Generated by the server once per upgrade, never metadata.client.id. */
  readonly connectionId: string;
}
type NativeClient = Effect.Success<ReturnType<PiWorkersPort["openView"]>>;
type ReadCaller = WorkerViewer | McpInvocationScope;
type Selection = typeof C.WorkerSelection.Type;
type Action = {
  digest: string;
  sequence: number;
  selectionKey: string;
  correlationConflict?: boolean;
  done: Deferred.Deferred<typeof C.WorkerActionOutcome.Type, C.ProviderWorkersError>;
};
type View = {
  viewer: WorkerViewer;
  target: Target;
  port: PiWorkersPort;
  client: NativeClient;
  viewId: string;
  recoveryHandle: string;
  grants: Set<typeof C.WorkerSensitiveGrant.Type>;
  stop: Deferred.Deferred<void>;
  closed: Deferred.Deferred<void>;
  events: Queue.Queue<typeof C.WorkerViewEvent.Type>;
  active: boolean;
  disconnectedAt?: number;
  selection: Selection | undefined;
  observedSelection: Selection | undefined;
  nativeFailed: boolean;
  terminalAuthority?: "lease_expired" | "stale_owner" | "unauthorized";
  sequence: number;
  admittedThrough: number;
  pending: boolean;
  actions: Map<string, Action>;
  lock: Semaphore.Semaphore;
};
const fail = (code: string) => Effect.fail(new C.ProviderWorkersError({ code }));
const mapError = (error: unknown) =>
  new C.ProviderWorkersError({
    code: typeof error === "object" && error !== null && "code" in error && typeof error.code === "string"
      ? error.code : "inspection_failed",
  });
const sameOwner = (a: typeof C.WorkerOwner.Type, b: typeof C.WorkerOwner.Type) =>
  a.processId === b.processId && a.coordinatorSessionId === b.coordinatorSessionId && a.epoch === b.epoch;
const selectionKey = (s: Selection) => JSON.stringify([
  s.processId, s.coordinatorSessionId, s.epoch, s.target.kind,
  s.target.kind === "background" ? s.target.instanceId : s.target.assignmentId,
  s.instanceId, s.generation, s.historyId, s.sessionId,
]);
const actionKey = (input: typeof C.WorkerActionInput.Type) => JSON.stringify([
  selectionKey(input.selection), input.operation.kind,
  input.operation.kind === "input" ? [
    input.operation.input.intent, input.operation.input.text, input.operation.input.decisionId ?? null,
  ] : null,
]);

/** Native detail/result always include both sections; a continuation must not repeat the other first page. */
export function workerContinuation<A extends object>(page: A, cursor?: typeof C.WorkerCursor.Type) {
  if (!cursor || !("section" in cursor)) return page;
  const result = Object.fromEntries(Object.entries(page));
  const omit = cursor.section === "brief" || cursor.section === "result_text"
    ? ["metadata", "nextMetadata"]
    : cursor.section === "detail_metadata" ? ["workbrief", "nextBrief"]
    : cursor.section === "result_metadata" ? ["text", "nextText"] : [];
  for (const key of omit) delete result[key];
  return result;
}

export const make = Effect.gen(function* () {
  const projection = yield* ProjectionStore.ProjectionStoreV2;
  const sessions = yield* ProviderSessionManager.ProviderSessionManagerV2;
  const environment = yield* ServerEnvironment.ServerEnvironment;
  const crypto = yield* Crypto.Crypto;
  const authSessions = yield* SessionStore.SessionStore;
  const serviceScope = yield* Scope.Scope;
  // Service lifetime, not an RPC handler lifetime. Closed leases are retained for T3 receipt lookup.
  const views = new Map<string, View>();
  const opening = new Map<PiWorkersPort, number>();
  const authorize = (viewer: ReadCaller, scope: C.AuthEnvironmentScope) =>
    ("session" in viewer ? viewer.session.scopes.includes(scope) :
      scope === C.AuthOrchestrationReadScope && viewer.capabilities.has("orchestration"))
      ? Effect.void : fail("forbidden");
  const operate = Effect.fn("ProviderWorkers.operate")(function* (viewer: WorkerViewer) {
    yield* authorize(viewer, C.AuthOrchestrationOperateScope);
    if (!(yield* authSessions.isActive(viewer.session.sessionId).pipe(Effect.mapError(() =>
      new C.ProviderWorkersError({ code: "forbidden" }))))) return yield* fail("forbidden");
  });
  const resident = Effect.fn("ProviderWorkers.resident")(function* (target: Target) {
    if (target.environmentId !== (yield* environment.getEnvironmentId)) return yield* fail("wrong_environment");
    const thread = yield* projection.getThreadShell(target.threadId).pipe(Effect.mapError(mapError));
    if (!thread) return yield* fail("unknown_thread");
    const binding = yield* projection.getThreadProviderContext(target.threadId).pipe(Effect.mapError(mapError));
    const providerThread = binding.providerThreads.find((item) => item.id === thread.activeProviderThreadId);
    const providerSessionId = providerThread?.providerSessionId;
    if (providerSessionId == null) return null;
    const runtime = yield* sessions.getResident(providerSessionId);
    if (Option.isNone(runtime)) return null;
    // The projection is the source of thread ownership; never resolve a client-supplied provider session.
    const port = runtime.value.workers;
    return port === undefined || !isPiWorkersPort(port) ? undefined : port;
  });
  const requiredPort = Effect.fn("ProviderWorkers.requiredPort")(function* (viewer: ReadCaller, target: Target) {
    yield* authorize(viewer, C.AuthOrchestrationReadScope);
    if (!("session" in viewer) && (viewer.environmentId !== target.environmentId ||
      (viewer.thread !== undefined && viewer.thread.threadId !== target.threadId))) return yield* fail("foreign_thread");
    const port = yield* resident(target);
    if (port === null) return yield* fail("runtime_absent");
    if (port === undefined) return yield* fail("unsupported");
    return port;
  });
  const decodePage = <A>(schema: Schema.Codec<A>, page: unknown) =>
    Effect.gen(function* () {
      const decoded = yield* Schema.decodeUnknownEffect(schema)(page).pipe(Effect.mapError(() => new C.ProviderWorkersError({ code: "invalid_page" })));
      // Includes the public envelope headroom. Native reply limit alone does not bound RPC buffers.
      if (new TextEncoder().encode(JSON.stringify(decoded)).length > 48 * 1024 - 1024) return yield* fail("oversized");
      return decoded;
    });
  const ordinary = <A>(
    schema: Schema.Codec<A>, viewer: ReadCaller, target: Target, read: (client: NativeClient) => Promise<unknown>,
  ) => Effect.gen(function* () {
    const port = yield* requiredPort(viewer, target);
    return yield* port.read(read).pipe(Effect.mapError(mapError), Effect.flatMap((page) => decodePage(schema, page)));
  });
  const ownView = Effect.fn("ProviderWorkers.ownView")(function* (
    viewer: WorkerViewer, input: typeof C.WorkerViewInput.Type,
    scope: C.AuthEnvironmentScope, allowDisconnected = false,
  ) {
    yield* authorize(viewer, scope);
    const port = yield* resident(input);
    const view = views.get(input.viewId);
    if (!view || !view.active || view.viewer.connectionId !== viewer.connectionId ||
      view.viewer.session.sessionId !== viewer.session.sessionId ||
      view.target.environmentId !== input.environmentId || view.target.threadId !== input.threadId)
      return yield* fail("foreign_view");
    if (view.nativeFailed && !allowDisconnected) return yield* fail("disconnected");
    if (port !== view.port || port?.observation.state !== "last_observation" ||
      !sameOwner(port.observation.owner, view.client.owner)) {
      yield* Deferred.succeed(view.stop, undefined);
      return yield* fail("stale_owner");
    }
    return view;
  });
  const event = (view: View): typeof C.WorkerViewEvent.Type => ({
    type: "opened", viewId: view.viewId, recoveryHandle: view.recoveryHandle,
    owner: view.client.owner, grants: [...view.grants],
  });
  const sensitive = <A>(
    schema: Schema.Codec<A>, viewer: WorkerViewer, input: typeof C.WorkerViewInput.Type,
    grant: typeof C.WorkerSensitiveGrant.Type, read: (client: NativeClient) => Promise<unknown>,
  ) => Effect.gen(function* () {
    const scope = grant === "history" ? C.AuthOrchestrationReadScope : C.AuthDiagnosticsReadScope;
    const view = yield* ownView(viewer, input, scope);
    if (!view.grants.has(grant)) return yield* fail("acknowledgement_required");
    const page = yield* Effect.tryPromise({ try: () => read(view.client), catch: mapError }).pipe(
      Effect.tapError(() => Deferred.succeed(view.stop, undefined)),
    );
    yield* ownView(viewer, input, scope);
    return yield* decodePage(schema, page);
  });
  const observe = (viewer: WorkerViewer, input: Target) => Stream.unwrap(Effect.gen(function* () {
    yield* authorize(viewer, C.AuthOrchestrationReadScope);
    const port = yield* resident(input);
    if (port === null) return Stream.make({ state: "runtime_absent" } as const);
    if (port === undefined) return Stream.make({ state: "unsupported" } as const);
    return port.observations.pipe(Stream.mapEffect((state) => decodePage(C.WorkerObservation, state)));
  }));
  const openView = (viewer: WorkerViewer, target: Target) => Stream.unwrap(Effect.gen(function* () {
    const port = yield* requiredPort(viewer, target);
    if (port.observation.state !== "last_observation") return yield* fail(port.observation.state);
    const now = yield* Clock.currentTimeMillis;
    for (const [id, view] of views) {
      if ((!view.active && now - (view.disconnectedAt ?? now) >= 5 * 60_000) ||
        (view.port === port && !sameOwner(view.client.owner, port.observation.owner))) views.delete(id);
    }
    const records = [...views.values()].filter((view) => view.port === port);
    const inFlight = opening.get(port) ?? 0;
    if (records.filter((view) => view.active).length + inFlight >= 3 || records.length + inFlight >= 16)
      return yield* fail("busy");
    opening.set(port, inFlight + 1);
    const view = yield* Effect.gen(function* () {
      const client = yield* port.openView().pipe(Effect.mapError((cause) => {
        const failure = classifyPiWorkerFailure(cause, "acquisition");
        return new C.ProviderWorkersError({ code: failure.kind === "coded" ? failure.code : "disconnected" });
      }));
      const view: View = {
        viewer, target, port, client,
        viewId: `view:${yield* crypto.randomUUIDv4.pipe(Effect.orDie)}`,
        recoveryHandle: `recovery:${yield* crypto.randomUUIDv4.pipe(Effect.orDie)}`,
        grants: new Set(), stop: yield* Deferred.make<void>(), closed: yield* Deferred.make<void>(),
        events: yield* Queue.sliding<typeof C.WorkerViewEvent.Type>(4), active: true,
        nativeFailed: false, sequence: 0, admittedThrough: 0, pending: false, actions: new Map(),
        selection: undefined, observedSelection: undefined,
        lock: yield* Semaphore.make(1),
      };
      views.set(view.viewId, view);
      return view;
    }).pipe(Effect.ensuring(Effect.sync(() => {
      const count = (opening.get(port) ?? 1) - 1;
      if (count === 0) opening.delete(port); else opening.set(port, count);
    })));
    const client = view.client;
    yield* Effect.addFinalizer(() => Effect.gen(function* () {
      view.active = false;
      view.grants.clear();
      view.selection = undefined;
      view.observedSelection = undefined;
      yield* port.disconnectView(client);
      view.disconnectedAt = yield* Clock.currentTimeMillis;
      yield* Deferred.succeed(view.closed, undefined);
    }));
    yield* port.observations.pipe(
      Stream.filter((state) => state.state !== "last_observation" || !sameOwner(state.owner, client.owner)),
      Stream.take(1), Stream.runDrain,
      Effect.andThen(Deferred.succeed(view.stop, undefined)), Effect.forkScoped,
    );
    return Stream.concat(Stream.make(event(view)), Stream.fromQueue(view.events)).pipe(
      Stream.interruptWhen(Deferred.await(view.stop)),
    );
  }));
  const closeView = Effect.fn("ProviderWorkers.closeView")(function* (viewer: WorkerViewer, input: typeof C.WorkerViewInput.Type) {
    const view = yield* ownView(viewer, input, C.AuthOrchestrationReadScope, true);
    view.active = false;
    view.grants.clear();
    yield* Deferred.succeed(view.stop, undefined);
    yield* Deferred.await(view.closed);
  });
  const acknowledge = Effect.fn("ProviderWorkers.acknowledge")(function* (viewer: WorkerViewer, input: typeof C.WorkerAcknowledgeInput.Type) {
    const scope = input.grant === "history" ? C.AuthOrchestrationReadScope : C.AuthDiagnosticsReadScope;
    const view = yield* ownView(viewer, input, scope);
    if (!view.port.ceilings[input.grant]) return yield* fail("ceiling_denied");
    yield* Effect.tryPromise({ try: () => view.client.grant(input.grant, true), catch: mapError });
    yield* ownView(viewer, input, scope);
    view.grants.add(input.grant);
    yield* Queue.offer(view.events, event(view));
  });
  const nativeFailure = (view: View) => Effect.sync(() => {
    view.nativeFailed = true;
    view.grants.clear();
    view.selection = undefined;
    view.observedSelection = undefined;
  }).pipe(Effect.andThen(Queue.offer(view.events, { type: "invalidated", reason: "disconnected" })));
  const nativeReadFailure = (view: View) => (error: C.ProviderWorkersError) =>
    error.code === "busy" ? Effect.void : nativeFailure(view);
  const currentSelection = Effect.fn("ProviderWorkers.currentSelection")(function* (view: View, selection: Selection) {
    const detail = yield* Effect.tryPromise({
      try: () => view.client.detail(selection.instanceId), catch: mapError,
    }).pipe(Effect.tapError(nativeReadFailure(view)));
    if (!detail.controls.selection || !sameOwner(selection, view.client.owner) ||
      selectionKey(detail.controls.selection) !== selectionKey(selection) ||
      (detail.status !== "created" && detail.status !== "running"))
      return yield* fail("stale_selection");
  });
  const controlDetail = Effect.fn("ProviderWorkers.controlDetail")(function* (
    viewer: WorkerViewer, input: typeof C.WorkerControlDetailInput.Type,
  ) {
    yield* operate(viewer);
    const view = yield* ownView(viewer, input, C.AuthOrchestrationOperateScope);
    return yield* view.lock.withPermit(Effect.gen(function* () {
      if (view.pending) return yield* fail("busy");
      const detail = yield* Effect.tryPromise({ try: () => view.client.detail(input.id), catch: mapError })
        .pipe(Effect.tapError(nativeReadFailure(view)));
      yield* operate(viewer);
      yield* ownView(viewer, input, C.AuthOrchestrationOperateScope);
      const page = yield* decodePage(C.WorkerControlDetail, detail);
      view.observedSelection = page.controls.selection;
      if (!page.controls.selection || !view.selection ||
        selectionKey(page.controls.selection) !== selectionKey(view.selection)) view.selection = undefined;
      return { ...page, controls: { ...page.controls, runtimeMode: view.port.runtimeMode,
        grant: view.selection ? "enabled" as const : "denied" as const } };
    }));
  });
  const activate = Effect.fn("ProviderWorkers.activate")(function* (
    viewer: WorkerViewer, input: typeof C.WorkerActivateInput.Type,
  ) {
    yield* operate(viewer);
    const view = yield* ownView(viewer, input, C.AuthOrchestrationOperateScope);
    yield* view.lock.withPermit(Effect.gen(function* () {
      if (view.pending) return yield* fail("busy");
      if (!view.port.ceilings.control) return yield* fail("ceiling_denied");
      if (!view.observedSelection || selectionKey(view.observedSelection) !== selectionKey(input.selection))
        return yield* fail("stale_selection");
      yield* currentSelection(view, input.selection);
      yield* operate(viewer);
      yield* ownView(viewer, input, C.AuthOrchestrationOperateScope);
      yield* Effect.tryPromise({
        try: () => view.client.grant("control", true, input.selection), catch: mapError,
      }).pipe(Effect.tapError(nativeReadFailure(view)));
      yield* ownView(viewer, input, C.AuthOrchestrationOperateScope);
      view.selection = input.selection;
    }));
  });
  const unknown = (
    actionId: string, reason: "unavailable" | "mapping_evicted" | "owner_retired" | "lease_expired" | "disconnected",
  ): typeof C.WorkerActionOutcome.Type => ({ actionId, status: { state: "outcome_unknown", reason } });
  const invalidateControl = (view: View, key: string) => Effect.gen(function* () {
    const selected = view.selection && selectionKey(view.selection) === key;
    const observed = view.observedSelection && selectionKey(view.observedSelection) === key;
    if (selected) view.selection = undefined;
    if (observed) view.observedSelection = undefined;
    if (selected || observed) yield* Queue.offer(view.events, { type: "invalidated", reason: "stale_selection" });
  });
  const retireAuthority = (view: View, code: NonNullable<View["terminalAuthority"]>) => Effect.gen(function* () {
    view.terminalAuthority = code;
    view.grants.clear();
    view.selection = undefined;
    view.observedSelection = undefined;
    yield* Deferred.succeed(view.stop, undefined);
    yield* Deferred.await(view.closed);
  });
  const terminalOutcome = (view: View, actionId: string) => view.terminalAuthority === "unauthorized"
    ? Effect.fail(new C.ProviderWorkersError({ code: "unauthorized", actionAdmitted: true }))
    : Effect.succeed(unknown(actionId, view.terminalAuthority === "lease_expired" ? "lease_expired" : "owner_retired"));
  const applyCode = (view: View, action: Action, code: string) => {
    if (code === "stale_selection" || code === "stale_reference" || code === "unknown_target")
      return invalidateControl(view, action.selectionKey);
    if (code === "lease_expired" || code === "stale_owner" || code === "unauthorized")
      return retireAuthority(view, code);
    return Effect.void;
  };
  const admittedFailure = (
    view: View, action: Action, actionId: string, failure: PiWorkerFailure, phase: "request" | "acquisition" = "request",
  ) => Effect.gen(function* () {
    if (failure.kind !== "coded") {
      if (phase === "request") yield* nativeFailure(view);
      return unknown(actionId, "disconnected");
    }
    yield* applyCode(view, action, failure.code);
    if (view.terminalAuthority) return yield* terminalOutcome(view, actionId);
    if (failure.code === "sequence_conflict") action.correlationConflict = true;
    return yield* Effect.fail(new C.ProviderWorkersError({ code: failure.code, actionAdmitted: true }));
  });
  const completed = (view: View, action: Action, actionId: string, page: unknown) =>
    decodePage(C.WorkerMutationStatus, page).pipe(
      Effect.flatMap((status) => applyCode(view, action,
        status.state === "recorded" && status.receipt.kind === "error" ? status.receipt.code : "").pipe(
        Effect.as({ actionId, status }))),
      Effect.catch(() => Effect.succeed(unknown(actionId, "unavailable"))),
    );
  const status = Effect.fn("ProviderWorkers.status")(function* (view: View, actionId: string, viewer: WorkerViewer) {
    const action = view.actions.get(actionId);
    if (!action) return unknown(actionId, "mapping_evicted");
    if (view.terminalAuthority) return yield* terminalOutcome(view, actionId);
    if (action.correlationConflict) return unknown(actionId, "unavailable");
    const lookup = (client: NativeClient) => operate(viewer).pipe(Effect.andThen(Effect.tryPromise({
      try: () => client.requestStatus(action.sequence), catch: (cause) => classifyPiWorkerFailure(cause),
    }).pipe(Effect.matchEffect({
      onSuccess: (page) => completed(view, action, actionId, page),
      onFailure: (failure) => admittedFailure(view, action, actionId, failure),
    }))));
    if (view.active && !view.nativeFailed) return yield* lookup(view.client);
    // The old socket must be joined before resume. Recovery is status-only, never a new lease.
    yield* view.port.disconnectView(view.client);
    view.grants.clear();
    view.selection = undefined;
    view.observedSelection = undefined;
    yield* operate(viewer);
    return yield* Effect.scoped(Effect.gen(function* () {
      return yield* view.port.openView(view.client.lease).pipe(
        Effect.mapError((cause) => classifyPiWorkerFailure(cause, "acquisition")),
        Effect.matchEffect({
          onSuccess: lookup,
          onFailure: (failure) => admittedFailure(view, action, actionId, failure, "acquisition"),
        }),
      );
    }));
  });
  const receipt = Effect.fn("ProviderWorkers.receipt")(function* (
    viewer: WorkerViewer, input: typeof C.WorkerReceiptInput.Type,
  ) {
    yield* operate(viewer);
    const access = input.access;
    const view = "viewId" in access ? views.get(access.viewId) :
      [...views.values()].find((view) => view.recoveryHandle === access.recoveryHandle);
    if (!view) return unknown(input.actionId, "unavailable");
    if (view.viewer.session.sessionId !== viewer.session.sessionId ||
      ("viewId" in access && ((!view.active && !view.terminalAuthority) || view.viewer.connectionId !== viewer.connectionId)) ||
      view.target.environmentId !== input.environmentId || view.target.threadId !== input.threadId)
      return yield* fail("foreign_view");
    const now = yield* Clock.currentTimeMillis;
    if (!view.active && now - (view.disconnectedAt ?? now) >= 5 * 60_000) {
      views.delete(view.viewId);
      return unknown(input.actionId, "unavailable");
    }
    const port = yield* resident(input);
    if (port !== view.port || port?.observation.state !== "last_observation" ||
      !sameOwner(port.observation.owner, view.client.owner)) return unknown(input.actionId, "owner_retired");
    return yield* view.lock.withPermit(operate(viewer).pipe(Effect.andThen(status(view, input.actionId, viewer))));
  });
  const action = Effect.fn("ProviderWorkers.action")(function* (
    viewer: WorkerViewer, input: typeof C.WorkerActionInput.Type,
  ) {
    yield* operate(viewer);
    const view = yield* ownView(viewer, input, C.AuthOrchestrationOperateScope, true);
    const registered = yield* view.lock.withPermit(Effect.gen(function* () {
      const previous = view.actions.get(input.actionId);
      if (previous) {
        if (previous.digest !== actionKey(input)) return yield* fail("action_conflict");
        return { outcome: yield* status(view, input.actionId, viewer) };
      }
      // An uninvoked ID stays uninvoked: busy precedes sequence/mapping/native work.
      if (view.pending) return yield* fail("busy");
      const decision = C.parseWorkerActionId(input.actionId);
      if (!decision || decision.viewId !== view.viewId) return yield* fail("invalid_action_id");
      // Absence below the frontier is not proof of non-admission. Later explicit
      // admission also supersedes older uninvoked decisions (amendment T3-1).
      if (decision.ordinal <= view.admittedThrough) return { outcome: unknown(input.actionId, "mapping_evicted") };
      if (view.nativeFailed) return yield* fail("disconnected");
      if (!view.port.ceilings.control) return yield* fail("ceiling_denied");
      if (!view.selection || selectionKey(view.selection) !== selectionKey(input.selection))
        return yield* fail("acknowledgement_required");
      if (input.operation.kind === "input" && view.port.runtimeMode !== "full-access")
        return yield* fail("full_access_required");
      yield* currentSelection(view, input.selection);
      yield* operate(viewer);
      yield* ownView(viewer, input, C.AuthOrchestrationOperateScope);
      const sequence = Math.max(view.sequence, view.client.lease.highWater) + 1;
      if (!Number.isSafeInteger(sequence)) return yield* fail("action_limit");
      const admitted: Action = { sequence, digest: actionKey(input), selectionKey: selectionKey(input.selection),
        done: yield* Deferred.make<typeof C.WorkerActionOutcome.Type, C.ProviderWorkersError>() };
      view.sequence = sequence;
      view.admittedThrough = decision.ordinal;
      view.actions.set(input.actionId, admitted);
      if (view.actions.size > 32) {
        const oldest = view.actions.keys().next().value;
        if (oldest !== undefined) view.actions.delete(oldest);
      }
      view.pending = true;
      const operation = input.operation;
      yield* Effect.tryPromise({
        try: () => operation.kind === "input"
          ? view.client.input(input.selection, operation.input, sequence)
          : view.client.cancel(input.selection, sequence),
        catch: (cause) => classifyPiWorkerFailure(cause),
      }).pipe(
        Effect.matchEffect({
          onSuccess: (page) => completed(view, admitted, input.actionId, page),
          onFailure: (failure) => admittedFailure(view, admitted, input.actionId, failure),
        }),
        Effect.onExit((exit) => Effect.sync(() => { view.pending = false; }).pipe(
          Effect.andThen(Deferred.done(admitted.done, exit)),
        )),
        Effect.interruptible,
        Effect.forkIn(serviceScope),
      );
      return { admitted };
    })).pipe(Effect.uninterruptible);
    return "outcome" in registered ? registered.outcome : yield* Deferred.await(registered.admitted.done);
  });
  return {
    readForMcp: (scope: McpInvocationScope, payload: typeof C.WorkerMcpReadInput.Type) => Effect.gen(function* () {
      yield* McpInvocationContext.requireThreadScope(scope, "Worker inspection");
      const input = payload.request;
      const target = { ...input, environmentId: scope.environmentId };
      const read: Effect.Effect<typeof C.WorkerMcpReadResult.Type, C.ProviderWorkersError> = input.operation === "list"
        ? ordinary(C.WorkerRoster, scope, target, (client) => client.list(input.after, input.revision))
        : input.operation === "detail"
        ? ordinary(C.WorkerDetail, scope, target, async (client) => workerContinuation(await client.detail(input.id, input.cursor), input.cursor))
        : input.operation === "requests"
        ? ordinary(C.WorkerRequests, scope, target, (client) => client.requests(input.id, input.cursor))
        : input.operation === "activity"
        ? ordinary(C.WorkerActivity, scope, target, (client) => client.activity(input.ref, input.cursor))
        : input.operation === "result"
        ? ordinary(C.WorkerResult, scope, target, async (client) => workerContinuation(await client.result(input.ref, input.cursor), input.cursor))
        : ordinary(C.WorkerHistoryList, scope, target, (client) => client.historyList({
          ...(input.workerId === undefined ? {} : { workerId: input.workerId }),
          ...(input.cursor === undefined ? {} : { cursor: input.cursor }),
        }));
      return yield* read.pipe(Effect.mapError((error) => new C.OrchestratorMcpFailure({
        code: error.code === "forbidden" || error.code === "foreign_thread" ? "capability_denied" : "provider_unavailable",
        message: `Worker inspection unavailable: ${error.code}.`,
      })));
    }),
    observe, openView, closeView, acknowledge, controlDetail, activate, action, receipt,
    list: (viewer: WorkerViewer, input: typeof C.WorkerListInput.Type) =>
      ordinary(C.WorkerRoster, viewer, input, (client) => client.list(input.after, input.revision)),
    detail: (viewer: WorkerViewer, input: typeof C.WorkerIdInput.Type) =>
      ordinary(C.WorkerDetail, viewer, input, async (client) => workerContinuation(await client.detail(input.id, input.cursor), input.cursor)),
    requests: (viewer: WorkerViewer, input: typeof C.WorkerIdInput.Type) =>
      ordinary(C.WorkerRequests, viewer, input, (client) => client.requests(input.id, input.cursor)),
    activity: (viewer: WorkerViewer, input: typeof C.WorkerRefInput.Type) =>
      ordinary(C.WorkerActivity, viewer, input, (client) => client.activity(input.ref, input.cursor)),
    result: (viewer: WorkerViewer, input: typeof C.WorkerRefInput.Type) =>
      ordinary(C.WorkerResult, viewer, input, async (client) => workerContinuation(await client.result(input.ref, input.cursor), input.cursor)),
    historyList: (viewer: WorkerViewer, input: typeof C.WorkerHistoryListInput.Type) =>
      ordinary(C.WorkerHistoryList, viewer, input, (client) => client.historyList({
        ...(input.workerId === undefined ? {} : { workerId: input.workerId }),
        ...(input.cursor === undefined ? {} : { cursor: input.cursor }),
        ...(input.limit === undefined ? {} : { limit: input.limit }),
      })),
    historyRead: (viewer: WorkerViewer, input: typeof C.WorkerHistoryReadInput.Type) =>
      sensitive(C.WorkerHistoryRead, viewer, input, "history", (client) => client.historyRead({
        historyId: input.historyId,
        ...(input.groupId === undefined ? {} : { groupId: input.groupId }),
        ...(input.workerId === undefined ? {} : { workerId: input.workerId }),
        ...(input.cursor === undefined ? {} : { cursor: input.cursor }),
        ...(input.limit === undefined ? {} : { limit: input.limit }),
      })),
    routeRead: (viewer: WorkerViewer, input: typeof C.WorkerRouteInput.Type) =>
      sensitive(C.WorkerRoute, viewer, input, "route", (client) => client.routeRead(input.id, input.offset)),
  };
});
export class ProviderWorkers extends Context.Service<ProviderWorkers, Effect.Success<typeof make>>()("t3/providerWorkers/ProviderWorkers") {}
export const layer = Layer.effect(ProviderWorkers, make);
